def frameworks(files, manifests):
    """'Framework (dependency version, manifest)' or 'Framework (marker file)', first sighting wins."""
    found = {}
    for m in manifests:
        for dep in m['runtime'] + m['dev']:
            name = dep.split()[0] if dep.split() else ''
            key = re.sub(r'/v\d+$', '', re.sub(r'\[.*\]', '', name).lower())
            label = FRAMEWORK_DEPS.get(key)
            if label and label not in found:
                found[label] = f'{label} ({dep}, {m["path"]})'
    for rel in files:
        if depth(rel) <= TOOLING_DEPTH:
            for pattern, label in FRAMEWORK_FILE_RULES:
                if pattern.fullmatch(rel) and label not in found:
                    found[label] = f'{label} ({rel})'
    return list(found.values())


def first_line(root, rel):
    line = read_text(root, rel).lstrip('﻿').split('\n', 1)[0].strip()
    return line if 0 < len(line) <= MAX_PIN_LEN else ''


def runtime_pins(root, rel):
    """Versions a root-level pin file holds, as 'Language version (file)' strings."""
    name = name_of(rel)
    if name in RUNTIME_PINS:
        line = first_line(root, rel)
        return [f'{RUNTIME_PINS[name]} {line} ({name})'] if line else []
    if name == '.tool-versions':
        out = []
        for line in read_text(root, rel).splitlines():
            words = line.split('#')[0].split()
            if len(words) >= 2:
                out.append(f'{words[0]} {words[1]} ({name})')
        return out[:MAX_TOOLING_ITEMS]
    if name in RUNTIME_FILES:
        return [name]
    return []


def section_tooling(root, files, manifests):
    found = {g: [] for g in GROUP_ORDER}
    counts = Counter()
    folders = Counter()
    managers = {}
    for rel in files:
        name, d = name_of(rel), depth(rel)
        if d == 0:
            found['runtime'] += runtime_pins(root, rel)
        if d <= 1 and name in LOCKFILES:
            managers.setdefault(LOCKFILES[name], rel)
        parts = rel.split('/')[:-1]
        matched = False
        for group, named, counted, dirs in TOOLING_RULES:
            if d <= TOOLING_DEPTH and not matched:
                for pattern in named:
                    m = pattern.fullmatch(rel)
                    if m:
                        shown = m.group('up') + m.group('dir') + '/' if m.groupdict().get('dir') else rel
                        if shown not in found[group]:
                            found[group].append(shown)
                        matched = True
                        break
            for pattern, label in counted:
                if pattern.fullmatch(name):
                    counts[(group, label)] += 1
                    break
            for i, part in enumerate(parts[:TOOLING_DEPTH + 1]):
                if part in dirs:
                    folders[(group, '/'.join(parts[:i + 1]) + '/')] += 1
                    break
    for tool, rel in sorted(managers.items(), key=lambda kv: (depth(kv[1]), kv[1])):
        found['package manager'].append(f'{tool} ({rel})')
    found['frameworks'] = frameworks(files, manifests)
    for m in manifests:
        found['runtime'] += [f'{t} ({m["path"]})' for t in m['toolchain']]
        if m['package_manager']:
            found['package manager'].append(f'{m["package_manager"]} ({m["path"]})')
        for tool in m['tools']:
            if tool in PYPROJECT_TOOLS:
                found[PYPROJECT_TOOLS[tool]].append(f'{m["path"]} [tool.{tool}]')
    out = ['## Tooling', '']
    lines = []
    labels = {group: [label for _, label in counted] for group, _, counted, _ in TOOLING_RULES}
    for group in GROUP_ORDER:
        items = list(found[group])
        items += [f'{counts[(group, label)]} {label}' for label in labels.get(group, [])
                  if counts[(group, label)]]
        for (g, folder), n in sorted(folders.items()):
            if g == group:
                items.append(f'{folder} ({n})')
        if items:
            lines.append(f'- {group}: {clip(items, MAX_TOOLING_ITEMS)}')
    return out + (lines or ['(none found)'])


# ---------------------------------------------------------------- git

MAX_BRANCHES = 12
MAX_SUBJECTS = 10
GIT_SAMPLE = 30          # recent commits examined for the merge style


def git_out(root, *args):
    try:
        out = subprocess.run(['git', *args], cwd=root, capture_output=True, text=True, timeout=30)
    except (OSError, subprocess.SubprocessError):
        return None
    return out.stdout if out.returncode == 0 else None


def section_git(root, in_git):
    out = ['## Git', '']
    if not in_git:
        return out + ['(not a git repository)']
    count = (git_out(root, 'rev-list', '--count', 'HEAD') or '').strip()
    if not count:
        return out + ['(no commits yet)']
    shallow = (git_out(root, 'rev-parse', '--is-shallow-repository') or '').strip() == 'true'
    refs = (git_out(root, 'for-each-ref', '--format=%(refname)', 'refs/heads', 'refs/remotes') or '').split()
    branches = [r.removeprefix('refs/heads/').removeprefix('refs/remotes/') for r in refs
                if not r.endswith('/HEAD')]
    sample = (git_out(root, 'log', f'-{GIT_SAMPLE}', '--format=%P%x09%s') or '').splitlines()
    parents = [line.split('\t', 1)[0] for line in sample]
    merges = sum(1 for p in parents if ' ' in p)
    prs = sum(1 for line in sample if re.search(r'\(#\d+\)$', line))
    subjects = [line.split('\t', 1)[1] for line, p in zip(sample, parents) if '\t' in line and ' ' not in p]
    out.append(f'- commits: {count}' + (' (shallow clone: history cut)' if shallow else ''))
    if branches:
        out.append(f'- branches: {clip(branches, MAX_BRANCHES)}')
    out.append(f'- last {len(sample)}: {merges} merge commits, {prs} subjects ending in (#N)')
    out.append('- recent subjects:')
    out += [f'  - {s}' for s in subjects[:MAX_SUBJECTS]]
    return out


def entry_reason(root, rel):
    """Why `rel` counts as an entry point, or None when it does not."""
    name = name_of(rel)
    stem, ext = PurePosixPath(name).stem, PurePosixPath(name).suffix.lower()
    d = depth(rel)
    if name == '__main__.py' and d <= 3:
        return 'Python package entry (__main__.py)'
    if stem in ENTRY_STEMS and ext in CODE_EXTS and d <= 2:
        return f'named {stem}.*'
    if 'bin' in rel.split('/')[:-1] and d <= 3:
        return 'file in bin/'
    if d == 0 and name in ROOT_ENTRY_NAMES:
        return {'flake.nix': 'Nix flake outputs'}.get(name, f'{name} at the root')
    if d == 1 and name in ('Makefile', 'Dockerfile'):
        return f'{name} in a subfolder'
    if d <= 1 and ext in SCRIPT_EXTS and os.access(root / rel, os.X_OK):
        if d == 0:
            return 'executable top-level script'
        folder = rel.split('/')[0]
        if folder not in TEST_DIRS:
            return f'executable script in {folder}/'
    return None


def section_entries(root, files, manifests):
    seen = {}
    known = set(files)
    for m in manifests:
        for path, reason, is_file in m['entries']:
            if is_file and path not in known:
                reason += NOT_IN_REPO
            seen.setdefault(path, reason)
    if any(rel.startswith('src/main/') for rel in files):
        seen.setdefault('src/main/', 'source root (src/main/)')
    for rel in files:
        reason = entry_reason(root, rel)
        if reason:
            seen.setdefault(rel, reason)
    out = ['## Entry points', '']
    if not seen:
        return out + ['(none found)']
    items = list(seen.items())
    for path, reason in items[:MAX_ENTRIES]:
        out.append(f'- `{path}` — {reason}')
    if len(items) > MAX_ENTRIES:
        out.append(f'- … {len(items) - MAX_ENTRIES} more')
    return out


def section_tree(files):
    counts = Counter()
    for rel in files:
        parts = rel.split('/')[:-1]
        for i in range(1, min(len(parts), TREE_DEPTH) + 1):
            counts[tuple(parts[:i])] += 1
        # deeper files still count toward their depth-3 ancestor (done above)
    out = ['## Tree', '']
    root_files = [rel for rel in files if '/' not in rel]
    if root_files:
        out.append(f'- ./ ({len(root_files)} files): {clip(root_files, MAX_ROOT_FILES)}')
    if not counts:
        return out + ['(no subdirectories)']
    rows = sorted(counts.items())
    # drop the deepest levels until the rows fit; top-level folders are never dropped
    for keep in range(TREE_DEPTH, 0, -1):
        shown = [r for r in rows if len(r[0]) <= keep]
        if len(shown) <= MAX_TREE_ROWS or keep == 1:
            break
    if keep < TREE_DEPTH:
        left = str(TREE_DEPTH) if keep == TREE_DEPTH - 1 else f'{keep + 1}-{TREE_DEPTH}'
        rows = shown
        out.append(f'(depth {left} left out: too many folders)')
    for parts, n in rows[:MAX_TREE_ROWS]:
        out.append(f'- {"/".join(parts)}/ ({n})')
    if len(rows) > MAX_TREE_ROWS:
        out.append(f'- … {len(rows) - MAX_TREE_ROWS} more folders')
    return out


def section_docs(root, files):
    readmes, agent_files, adr_dirs, docs, old_maps = [], [], set(), [], 0
    for rel in files:
        name, d = name_of(rel), depth(rel)
        if name.upper().startswith('README') and d <= 2:
            readmes.append(rel)
        if name in DOC_NAMES and d <= 2:
            agent_files.append(rel)
        parts = rel.split('/')
        for i, part in enumerate(parts[:-1]):
            if part.lower() in ADR_NAMES and i <= 3:
                adr_dirs.add('/'.join(parts[:i + 1]))
        if rel.startswith('docs/CODEMAPS/'):
            old_maps += 1
        elif rel.startswith('docs/') and rel != REPORT_PATH:
            docs.append(rel)
    out = ['## Docs', '']
    if not (readmes or agent_files or docs or old_maps):
        return out + ['(none found)']
    for rel in readmes + agent_files:
        out.append(f'- `{rel}`')
    for adr in sorted(adr_dirs):
        out.append(f'- ADR folder: `{adr}/`')
    if docs:
        out.append(f'- `docs/` ({len(docs)} files):')
        for rel in docs[:MAX_DOCS]:
            out.append(f'  - `{rel}`')
        if len(docs) > MAX_DOCS:
            out.append(f'  - … {len(docs) - MAX_DOCS} more')
    if old_maps:
        out.append(f'- `docs/CODEMAPS/` ({old_maps} files): old codemap output; ignored')
    return out


# ---------------------------------------------------------------- main

def build(root):
    files, in_git = list_files(root)
    manifests = load_manifests(root, files)
    blocks = [
        section_header(root, files, in_git),
        section_languages(root, files),
        section_manifests(manifests),
        section_tooling(root, files, manifests),
        section_git(root, in_git),
        section_entries(root, files, manifests),
        section_tree(files),
        section_docs(root, files),
    ]
    lines = []
    for block in blocks:
        while block and block[-1] == '':
            block = block[:-1]
        lines += block + ['']
    if len(lines) > MAX_LINES:
        lines = lines[:MAX_LINES - 1] + [f'(output cut at {MAX_LINES} lines)']
    return '\n'.join(lines).rstrip() + '\n'


def main(argv):
    if len(argv) > 2 or (len(argv) == 2 and argv[1] in ('-h', '--help')):
        print(__doc__, file=sys.stderr)
        return 2
    arg = argv[1] if len(argv) == 2 else '.'
    root = Path(arg).resolve()
    if not root.is_dir():
        print(f'error: not a directory: {arg}', file=sys.stderr)
        return 2
    sys.stdout.write(build(root))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))

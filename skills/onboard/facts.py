#!/usr/bin/env python3
"""Print a Markdown fact summary of a repository to stdout.

Usage: python3 facts.py [ROOT]      (ROOT defaults to the current directory)

Reads the repo and writes nothing. Standard library only, Python 3.11+.
All paths in the output are relative to ROOT.
"""
import datetime
import json
import os
import re
import subprocess
import sys
import tomllib
from collections import Counter
from pathlib import Path, PurePosixPath

NOISE_DIRS = {
    '.git', 'node_modules', 'dist', 'build', 'out', '.next', '.nuxt', 'target',
    'vendor', '.venv', 'venv', '__pycache__', 'coverage', '.cache', '.turbo',
}
MAX_LINES = 300
MAX_READ = 2_000_000
MAX_MANIFESTS = 15
MAX_DEPS = 25

LANGUAGES = {
    '.py': 'Python', '.pyi': 'Python', '.js': 'JavaScript', '.mjs': 'JavaScript',
    '.cjs': 'JavaScript', '.jsx': 'JavaScript (JSX)', '.ts': 'TypeScript',
    '.mts': 'TypeScript', '.cts': 'TypeScript', '.tsx': 'TypeScript (TSX)',
    '.go': 'Go', '.rs': 'Rust', '.rb': 'Ruby', '.java': 'Java', '.kt': 'Kotlin',
    '.swift': 'Swift', '.c': 'C', '.h': 'C/C++ header', '.cc': 'C++', '.cpp': 'C++',
    '.hpp': 'C++', '.cs': 'C#', '.php': 'PHP', '.lua': 'Lua', '.ex': 'Elixir',
    '.exs': 'Elixir', '.sh': 'Shell', '.bash': 'Shell', '.zsh': 'Shell',
    '.fish': 'Shell', '.nix': 'Nix', '.md': 'Markdown', '.mdx': 'Markdown',
    '.json': 'JSON', '.jsonc': 'JSON', '.yml': 'YAML', '.yaml': 'YAML',
    '.toml': 'TOML', '.html': 'HTML', '.css': 'CSS', '.scss': 'CSS',
    '.sql': 'SQL', '.vue': 'Vue', '.svelte': 'Svelte', '.tf': 'Terraform',
    '.proto': 'Protobuf', '.txt': 'Text',
}
CODE_EXTS = {
    '.py', '.js', '.mjs', '.cjs', '.jsx', '.ts', '.mts', '.cts', '.tsx', '.go',
    '.rs', '.rb', '.java', '.kt', '.swift', '.c', '.cc', '.cpp', '.cs', '.php',
    '.lua', '.ex', '.exs', '.sh', '.bash', '.zsh', '.nix', '.vue', '.svelte',
}
ENTRY_STEMS = {'main', 'index', 'app', 'cli'}
DOC_NAMES = {'AGENTS.md', 'CLAUDE.md', 'GEMINI.md'}
ADR_NAMES = {'adr', 'adrs', 'decisions', 'architecture-decisions'}
REPORT_PATH = '.agents/onboarding.md'
REPORT_HEADER = '<!-- Generated by onboard:'


# ---------------------------------------------------------------- file list

def git_files(root):
    """Tracked plus untracked-not-ignored files, or None when not in a git repo."""
    try:
        inside = subprocess.run(
            ['git', 'rev-parse', '--is-inside-work-tree'], cwd=root,
            capture_output=True, text=True, timeout=30)
        if inside.returncode != 0 or inside.stdout.strip() != 'true':
            return None
        out = subprocess.run(
            ['git', 'ls-files', '-z', '--cached', '--others', '--exclude-standard'],
            cwd=root, capture_output=True, timeout=60)
    except (OSError, subprocess.SubprocessError):
        return None
    if out.returncode != 0:
        return None
    names = {n.decode('utf-8', 'replace') for n in out.stdout.split(b'\0') if n}
    return sorted(n for n in names if (root / n).is_file())


def walk_files(root):
    found = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if d not in NOISE_DIRS)
        rel = Path(dirpath).relative_to(root)
        for name in sorted(filenames):
            path = rel / name
            if (root / path).is_file():
                found.append(path.as_posix())
    return sorted(found)


def list_files(root):
    files = git_files(root)
    if files is None:
        return walk_files(root), False
    return files, True


# ---------------------------------------------------------------- helpers

def read_text(root, rel):
    try:
        with open(root / rel, 'rb') as fh:
            return fh.read(MAX_READ).decode('utf-8', 'replace')
    except OSError:
        return ''


def depth(rel):
    return rel.count('/')


def name_of(rel):
    return rel.rsplit('/', 1)[-1]


def language_of(rel):
    name = name_of(rel)
    ext = PurePosixPath(name).suffix.lower()
    if ext in LANGUAGES:
        return LANGUAGES[ext]
    if name in ('Makefile', 'Dockerfile', 'justfile'):
        return name
    if ext:
        return f'other ({ext})'
    if name.startswith('.'):
        return f'other ({name})'
    return 'other (no ext)'


def count_lines(root, rel):
    try:
        with open(root / rel, 'rb') as fh:
            data = fh.read(MAX_READ)
    except OSError:
        return 0
    if b'\0' in data[:4096]:
        return 0
    return data.count(b'\n') + (1 if data and not data.endswith(b'\n') else 0)


def clip(items, limit=MAX_DEPS):
    shown = items[:limit]
    text = ', '.join(shown)
    if len(items) > limit:
        text += f', … +{len(items) - limit} more'
    return text


def pep508(spec):
    m = re.match(r'\s*([A-Za-z0-9_.\-]+(?:\[[^\]]*\])?)\s*(.*)', spec)
    if not m:
        return spec.strip()
    rest = m.group(2).split(';')[0].strip()
    return f'{m.group(1)} {rest}'.strip()


def new_manifest(rel, kind):
    return {'path': rel, 'kind': kind, 'name': None, 'version': None,
            'runtime': [], 'dev': [], 'notes': [], 'entries': []}


# ---------------------------------------------------------------- manifests

def parse_package_json(rel, text):
    m = new_manifest(rel, 'npm')
    data = json.loads(text)
    if not isinstance(data, dict):
        raise ValueError('not an object')
    m['name'], m['version'] = data.get('name'), data.get('version')
    for key, bucket in (('dependencies', 'runtime'), ('devDependencies', 'dev')):
        deps = data.get(key)
        if isinstance(deps, dict):
            m[bucket] = [f'{k} {v}' for k, v in deps.items()]
    peers = data.get('peerDependencies')
    if isinstance(peers, dict):
        m['notes'].append('peer: ' + clip([f'{k} {v}' for k, v in peers.items()], 10))
    if data.get('workspaces'):
        m['notes'].append('workspaces: ' + json.dumps(data['workspaces'])[:120])
    base = rel.rsplit('/', 1)[0] + '/' if '/' in rel else ''
    for key in ('main', 'module'):
        if isinstance(data.get(key), str):
            m['entries'].append((base + data[key].removeprefix('./'), f'{rel} "{key}"'))
    binv = data.get('bin')
    if isinstance(binv, str):
        m['entries'].append((base + binv.removeprefix('./'), f'{rel} "bin"'))
    elif isinstance(binv, dict):
        for cmd, target in binv.items():
            if isinstance(target, str):
                m['entries'].append((base + target.removeprefix('./'), f'{rel} bin "{cmd}"'))
    scripts = data.get('scripts')
    if isinstance(scripts, dict):
        for key, cmd in list(scripts.items())[:8]:
            m['entries'].append((f'{rel} scripts.{key}', f'`{str(cmd)[:60]}`'))
    return m


def poetry_dep_list(table):
    out = []
    for k, v in table.items():
        if k.lower() == 'python':
            continue
        spec = v if isinstance(v, str) else (v.get('version', '') if isinstance(v, dict) else '')
        out.append(f'{k} {spec}'.strip())
    return out


def parse_pyproject(rel, text):
    m = new_manifest(rel, 'python')
    data = tomllib.loads(text)
    project = data.get('project', {})
    poetry = data.get('tool', {}).get('poetry', {})
    m['name'] = project.get('name') or poetry.get('name')
    m['version'] = project.get('version') or poetry.get('version')
    if project.get('requires-python'):
        m['notes'].append(f'requires-python: {project["requires-python"]}')
    m['runtime'] = [pep508(d) for d in project.get('dependencies', [])]
    m['runtime'] += poetry_dep_list(poetry.get('dependencies', {}))
    for group in project.get('optional-dependencies', {}).values():
        m['dev'] += [pep508(d) for d in group]
    for group in data.get('dependency-groups', {}).values():
        m['dev'] += [pep508(d) for d in group if isinstance(d, str)]
    m['dev'] += poetry_dep_list(poetry.get('dev-dependencies', {}))
    for group in poetry.get('group', {}).values():
        m['dev'] += poetry_dep_list(group.get('dependencies', {}))
    scripts = dict(project.get('scripts', {}))
    scripts.update(poetry.get('scripts', {}))
    for cmd, target in scripts.items():
        m['entries'].append((f'{rel} script "{cmd}"', f'-> {target}'))
    return m


def parse_requirements(rel, text):
    m = new_manifest(rel, 'python requirements')
    bucket = 'dev' if re.search(r'dev|test', name_of(rel)) else 'runtime'
    for line in text.splitlines():
        line = line.split('#')[0].strip()
        if line and not line.startswith('-'):
            m[bucket].append(pep508(line))
    return m


def parse_go_mod(rel, text):
    m = new_manifest(rel, 'go')
    mod = re.search(r'^module\s+(\S+)', text, re.M)
    m['name'] = mod.group(1) if mod else None
    go = re.search(r'^go\s+(\S+)', text, re.M)
    if go:
        m['notes'].append(f'go: {go.group(1)}')
    in_block = False
    for line in text.splitlines():
        line = line.split('//')[0].strip()
        if line.startswith('require ('):
            in_block = True
        elif in_block and line == ')':
            in_block = False
        elif in_block and line:
            m['runtime'].append(' '.join(line.split()[:2]))
        elif line.startswith('require '):
            m['runtime'].append(' '.join(line.split()[1:3]))
    return m


def cargo_dep_list(table):
    out = []
    for k, v in table.items():
        if isinstance(v, str):
            spec = v
        elif isinstance(v, dict):
            spec = v.get('version') or (f'path {v["path"]}' if 'path' in v else
                                        f'git {v["git"]}' if 'git' in v else '')
        else:
            spec = ''
        out.append(f'{k} {spec}'.strip())
    return out


def parse_cargo(rel, text):
    m = new_manifest(rel, 'rust')
    data = tomllib.loads(text)
    pkg = data.get('package', {})
    m['name'], m['version'] = pkg.get('name'), pkg.get('version')
    m['runtime'] = cargo_dep_list(data.get('dependencies', {}))
    m['runtime'] += cargo_dep_list(data.get('workspace', {}).get('dependencies', {}))
    m['dev'] = cargo_dep_list(data.get('dev-dependencies', {}))
    m['dev'] += cargo_dep_list(data.get('build-dependencies', {}))
    if data.get('workspace', {}).get('members'):
        m['notes'].append('workspace members: ' + clip(data['workspace']['members'], 10))
    base = rel.rsplit('/', 1)[0] + '/' if '/' in rel else ''
    for b in data.get('bin', []):
        if isinstance(b, dict):
            m['entries'].append((base + b.get('path', 'src/main.rs'),
                                 f'{rel} [[bin]] "{b.get("name", "")}"'))
    if (data.get('lib') or {}).get('path'):
        m['entries'].append((base + data['lib']['path'], f'{rel} [lib]'))
    return m


def balanced_block(text, start):
    """Text after an opening brace at `start` up to its matching close brace."""
    level = 1
    for i in range(start, len(text)):
        if text[i] == '{':
            level += 1
        elif text[i] == '}':
            level -= 1
            if level == 0:
                return text[start:i]
    return text[start:]


def parse_flake(rel, text):
    m = new_manifest(rel, 'nix flake')
    desc = re.search(r'description\s*=\s*"([^"]*)"', text)
    m['name'] = desc.group(1) if desc else None
    found = {}
    for mm in re.finditer(r'\binputs\.([\w-]+)\.url\s*=\s*"([^"]+)"', text):
        found.setdefault(mm.group(1), mm.group(2))
    block_start = re.search(r'\binputs\s*=\s*\{', text)
    if block_start:
        block = balanced_block(text, block_start.end())
        for mm in re.finditer(r'(?<![\w.-])([\w-]+)\.url\s*=\s*"([^"]+)"', block):
            found.setdefault(mm.group(1), mm.group(2))
        for mm in re.finditer(r'(?<![\w.-])([\w-]+)\s*=\s*\{([^{}]*)\}', block):
            url = re.search(r'\burl\s*=\s*"([^"]+)"', mm.group(2))
            if url:
                found.setdefault(mm.group(1), url.group(1))
    m['runtime'] = [f'{k} {v}' for k, v in found.items()]
    return m


def parse_manifest(rel, text):
    name = name_of(rel)
    if name == 'package.json':
        return parse_package_json(rel, text)
    if name == 'pyproject.toml':
        return parse_pyproject(rel, text)
    if re.fullmatch(r'requirements.*\.txt', name):
        return parse_requirements(rel, text)
    if name == 'go.mod':
        return parse_go_mod(rel, text)
    if name == 'Cargo.toml':
        return parse_cargo(rel, text)
    return parse_flake(rel, text)


def is_manifest(rel):
    name = name_of(rel)
    return (name in ('package.json', 'pyproject.toml', 'go.mod', 'Cargo.toml', 'flake.nix')
            or re.fullmatch(r'requirements.*\.txt', name) is not None)


def load_manifests(root, files):
    """Parse manifests; skip any under a noise dir (git may track vendored ones)."""
    out = []
    for rel in files:
        if not is_manifest(rel) or NOISE_DIRS & set(rel.split('/')[:-1]):
            continue
        try:
            out.append(parse_manifest(rel, read_text(root, rel)))
        except (ValueError, tomllib.TOMLDecodeError) as exc:
            bad = new_manifest(rel, 'unparseable')
            bad['notes'].append(f'could not parse: {type(exc).__name__}')
            out.append(bad)
    out.sort(key=lambda m: (depth(m['path']), m['path']))
    return out


# ---------------------------------------------------------------- sections

def report_status(root):
    if not (root / REPORT_PATH).is_file():
        return 'absent'
    first = read_text(root, REPORT_PATH).lstrip('\ufeff').split('\n', 1)[0]
    if not first.startswith(REPORT_HEADER):
        return 'hand-written'
    m = re.match(r'\s*(\d{4}-\d{2}-\d{2})', first[len(REPORT_HEADER):])
    return f'generated {m.group(1)}' if m else 'generated'


def section_header(root, files, in_git):
    return [
        f'# Repo facts: {root.name}', '',
        f'- files: {len(files)}',
        f'- git: {"yes (tracked + untracked, ignored files left out)" if in_git else "no (walked the directory, skipped noise dirs)"}',
        f'- date: {datetime.date.today().isoformat()}',
        f'- report: `{REPORT_PATH}` — {report_status(root)}',
    ]


def section_languages(root, files):
    stats = {}
    for rel in files:
        lang = language_of(rel)
        count, lines = stats.get(lang, (0, 0))
        stats[lang] = (count + 1, lines + count_lines(root, rel))
    out = ['## Languages', '']
    if not stats:
        return out + ['(no files)']
    out += ['| language | files | lines |', '|---|---|---|']
    ranked = sorted(stats.items(), key=lambda kv: (-kv[1][0], kv[0]))
    for lang, (count, lines) in ranked[:15]:
        out.append(f'| {lang} | {count} | {lines} |')
    if len(ranked) > 15:
        out.append(f'| … {len(ranked) - 15} more | | |')
    return out


def section_manifests(manifests):
    out = ['## Manifests', '']
    if not manifests:
        return out + ['(none found)']
    for m in manifests[:MAX_MANIFESTS]:
        title = f'### {m["path"]}'
        ident = ' '.join(x for x in (m['name'], m['version']) if x)
        out.append(f'{title} ({m["kind"]})' + (f' — {ident}' if ident else ''))
        for note in m['notes']:
            out.append(f'- {note}')
        if m['runtime']:
            label = 'inputs' if m['kind'] == 'nix flake' else 'runtime'
            out.append(f'- {label} ({len(m["runtime"])}): {clip(m["runtime"])}')
        if m['dev']:
            out.append(f'- dev ({len(m["dev"])}): {clip(m["dev"])}')
        out.append('')
    if len(manifests) > MAX_MANIFESTS:
        out.append(f'… {len(manifests) - MAX_MANIFESTS} more manifests not shown')
    return out


def section_entries(root, files, manifests):
    seen = {}

    def add(path, reason):
        seen.setdefault(path, reason)

    for m in manifests:
        for path, reason in m['entries']:
            add(path, reason)
    for rel in files:
        name = name_of(rel)
        stem, ext = PurePosixPath(name).stem, PurePosixPath(name).suffix.lower()
        d = depth(rel)
        if name == '__main__.py' and d <= 3:
            add(rel, 'Python package entry (__main__.py)')
        elif stem in ENTRY_STEMS and ext in CODE_EXTS and d <= 2:
            add(rel, f'named {stem}.*')
        elif 'bin' in rel.split('/')[:-1] and d <= 3:
            add(rel, 'file in bin/')
        elif d == 0 and name in ('Makefile', 'Dockerfile', 'flake.nix', 'justfile'):
            add(rel, {'flake.nix': 'Nix flake outputs'}.get(name, f'{name} at the root'))
        elif d == 1 and name in ('Makefile', 'Dockerfile'):
            add(rel, f'{name} in a subfolder')
        elif d == 0 and os.access(root / rel, os.X_OK) and ext in ('', '.sh', '.py', '.js', '.rb'):
            add(rel, 'executable top-level script')
    out = ['## Entry points', '']
    if not seen:
        return out + ['(none found)']
    items = list(seen.items())
    for path, reason in items[:40]:
        out.append(f'- `{path}` — {reason}')
    if len(items) > 40:
        out.append(f'- … {len(items) - 40} more')
    return out


def section_tree(files):
    counts = Counter()
    for rel in files:
        parts = rel.split('/')[:-1]
        for i in range(1, min(len(parts), 3) + 1):
            counts[tuple(parts[:i])] += 1
        # deeper files still count toward their depth-3 ancestor (done above)
    out = ['## Tree', '']
    if not counts:
        return out + ['(no subdirectories)']
    rows = sorted(counts.items())
    limit = 70
    if len(rows) > limit:
        rows2 = [r for r in rows if len(r[0]) <= 2]
        if len(rows2) <= limit:
            rows = rows2
            out.append('(depth 3 left out: too many folders)')
    for parts, n in rows[:limit]:
        out.append(f'- {"/".join(parts)}/ ({n})')
    if len(rows) > limit:
        out.append(f'- … {len(rows) - limit} more folders')
    return out


def section_docs(root, files):
    readmes, agent_files, adr_dirs, docs, old_maps = [], [], set(), [], 0
    for rel in files:
        name, d = name_of(rel), depth(rel)
        if name.upper().startswith('README') and d <= 2:
            readmes.append(rel)
        if name in DOC_NAMES and d <= 2:
            agent_files.append(rel)
        parts = rel.split('/')
        for i, part in enumerate(parts[:-1]):
            if part.lower() in ADR_NAMES and i <= 3:
                adr_dirs.add('/'.join(parts[:i + 1]))
        if rel.startswith('docs/CODEMAPS/') and rel.endswith('.md') and d == 2:
            old_maps += 1
        elif rel.startswith('docs/'):
            docs.append(rel)
    out = ['## Docs', '']
    if not (readmes or agent_files or docs or old_maps):
        return out + ['(none found)']
    for rel in readmes + agent_files:
        out.append(f'- `{rel}`')
    for adr in sorted(adr_dirs):
        out.append(f'- ADR folder: `{adr}/`')
    if docs:
        out.append(f'- `docs/` ({len(docs)} files):')
        for rel in docs[:25]:
            out.append(f'  - `{rel}`')
        if len(docs) > 25:
            out.append(f'  - … {len(docs) - 25} more')
    if old_maps:
        out.append(f'- `docs/CODEMAPS/` ({old_maps} files): old codemap output; ignored')
    return out


# ---------------------------------------------------------------- main

def build(root):
    files, in_git = list_files(root)
    manifests = load_manifests(root, files)
    blocks = [
        section_header(root, files, in_git),
        section_languages(root, files),
        section_manifests(manifests),
        section_entries(root, files, manifests),
        section_tree(files),
        section_docs(root, files),
    ]
    lines = []
    for block in blocks:
        while block and block[-1] == '':
            block = block[:-1]
        lines += block + ['']
    if len(lines) > MAX_LINES:
        lines = lines[:MAX_LINES - 1] + ['(output cut at 300 lines)']
    return '\n'.join(lines).rstrip() + '\n'


def main(argv):
    if len(argv) > 2 or (len(argv) == 2 and argv[1] in ('-h', '--help')):
        print(__doc__, file=sys.stderr)
        return 2
    root = Path(argv[1] if len(argv) == 2 else '.').resolve()
    if not root.is_dir():
        print(f'error: not a directory: {argv[1] if len(argv) == 2 else "."}', file=sys.stderr)
        return 2
    sys.stdout.write(build(root))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))

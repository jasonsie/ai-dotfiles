#!/usr/bin/env bash
# scripts/adapters/rules.sh — Generate AGENTS.md, GEMINI.md and update CLAUDE.md
#
# Entry point: rules_adapter_run

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "${SCRIPT_DIR}/_common.sh"

WORKSPACE_DIR="${WORKSPACE_DIR:-$(cd "${SCRIPT_DIR}/../.." && pwd)}"

# ---------------------------------------------------------------------------
# Build a concatenated rule file for a given CLI target
# Returns the content on stdout
# ---------------------------------------------------------------------------
_build_rules_for_target() {
  local target="$1"
  local header="$2"

  python3 - "${WORKSPACE_DIR}/tools/rules/manifest.yaml" \
            "${WORKSPACE_DIR}/tools/rules" \
            "$target" \
            "$header" <<'PYEOF'
import sys, os, yaml, re

manifest_path = sys.argv[1]
rules_dir     = sys.argv[2]
target        = sys.argv[3]
header        = sys.argv[4]

with open(manifest_path) as f:
    manifest = yaml.safe_load(f)

rules = manifest.get('rules', {})

# Sort by order field
sorted_rules = sorted(rules.items(), key=lambda kv: kv[1].get('order', 999))

sections = []
for rule_key, rule_meta in sorted_rules:
    targets = rule_meta.get('targets', [])
    if target not in targets:
        continue

    rule_file = os.path.join(rules_dir, rule_meta.get('file', ''))
    if not os.path.isfile(rule_file):
        continue

    with open(rule_file) as f:
        content = f.read()

    # Strip YAML frontmatter if present
    fm_match = re.match(r'^---\s*\n.*?\n---\s*\n', content, re.DOTALL)
    if fm_match:
        content = content[fm_match.end():]

    sections.append(content.strip())

body = '\n\n---\n\n'.join(sections)
# Ensure header ends with a blank line before the body
output = header.rstrip('\n') + '\n\n' + body + '\n'
print(output, end='')
PYEOF
}

# ---------------------------------------------------------------------------
# Update CLAUDE.md — replace only the ## 常駐規則 section
# ---------------------------------------------------------------------------
_update_claude_md() {
  python3 - "${WORKSPACE_DIR}/CLAUDE.md" \
            "${WORKSPACE_DIR}/tools/rules/manifest.yaml" \
            "${WORKSPACE_DIR}" <<'PYEOF'
import sys, os, yaml, re

claude_md_path = sys.argv[1]
manifest_path  = sys.argv[2]
workspace_dir  = sys.argv[3]

with open(claude_md_path) as f:
    original = f.read()

with open(manifest_path) as f:
    manifest = yaml.safe_load(f)

rules = manifest.get('rules', {})
sorted_rules = sorted(rules.items(), key=lambda kv: kv[1].get('order', 999))

# Build the new 常駐規則 section lines
import_lines = []
for rule_key, rule_meta in sorted_rules:
    targets = rule_meta.get('targets', [])
    if 'claude' not in targets:
        continue
    rule_file = rule_meta.get('file', '')
    import_lines.append(f'- @.claude/rules/{rule_file}')

new_section = '## 常駐規則（🟡 自動載入，約 1,184 tok）\n\n' + '\n'.join(import_lines)

# Find the 常駐規則 heading and replace until the next ## heading
pattern = r'(## 常駐規則[^\n]*\n)(.*?)(?=\n## |\Z)'
replacement = new_section + '\n'

updated, count = re.subn(pattern, replacement, original, count=1, flags=re.DOTALL)

if count == 0:
    # Section not found — append it
    updated = original.rstrip() + '\n\n' + new_section + '\n'

print(updated, end='')
PYEOF
}

# ---------------------------------------------------------------------------
# Main entry point
# ---------------------------------------------------------------------------
rules_adapter_run() {
  log_info "=== Rules adapter ==="

  local agents_header
  agents_header="$(cat <<'HDR'
# AGENTS.md — Cross-CLI Agent Rules

> Generated by `scripts/adapters/rules.sh`. Edit `tools/rules/*.md` instead.

HDR
)"

  local gemini_header
  gemini_header="$(cat <<'HDR'
# GEMINI.md — Cross-CLI Agent Rules

> Generated by `scripts/adapters/rules.sh`. Edit `tools/rules/*.md` instead.

HDR
)"

  # 1. Generate AGENTS.md (portable rules that include codex)
  log_info "Generating AGENTS.md..."
  local agents_content
  agents_content="$(_build_rules_for_target "codex" "$agents_header")"
  write_if_changed "${WORKSPACE_DIR}/AGENTS.md" "$agents_content"

  # 2. Generate GEMINI.md (portable rules that include gemini)
  log_info "Generating GEMINI.md..."
  local gemini_content
  gemini_content="$(_build_rules_for_target "gemini" "$gemini_header")"
  write_if_changed "${WORKSPACE_DIR}/GEMINI.md" "$gemini_content"

  # 3. Update CLAUDE.md — surgical replacement of 常駐規則 section
  log_info "Updating CLAUDE.md (常駐規則 section)..."
  local updated_claude
  updated_claude="$(_update_claude_md)"
  write_if_changed "${WORKSPACE_DIR}/CLAUDE.md" "$updated_claude"

  log_ok "Rules adapter done."
}

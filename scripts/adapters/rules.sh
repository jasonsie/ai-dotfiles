#!/usr/bin/env bash
# scripts/adapters/rules.sh — Generate AGENTS.md, GEMINI.md and update CLAUDE.md
#
# Entry point: rules_adapter_run

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "${SCRIPT_DIR}/_common.sh"

WORKSPACE_DIR="${WORKSPACE_DIR:-$(cd "${SCRIPT_DIR}/../.." && pwd)}"

# ---------------------------------------------------------------------------
# Build a concatenated rule file for a given CLI target
# Returns the content on stdout
# ---------------------------------------------------------------------------
_build_rules_for_target() {
  local target="$1"
  local header="$2"

  python3 - "${WORKSPACE_DIR}/tools/rules/manifest.yaml" \
            "${WORKSPACE_DIR}/tools/rules" \
            "$target" \
            "$header" <<'PYEOF'
import sys, os, yaml, re

manifest_path = sys.argv[1]
rules_dir     = sys.argv[2]
target        = sys.argv[3]
header        = sys.argv[4]

with open(manifest_path) as f:
    manifest = yaml.safe_load(f)

rules = manifest.get('rules', {})

# Sort by order field
sorted_rules = sorted(rules.items(), key=lambda kv: kv[1].get('order', 999))

sections = []
for rule_key, rule_meta in sorted_rules:
    targets = rule_meta.get('targets', [])
    if target not in targets:
        continue

    rule_file = os.path.join(rules_dir, rule_meta.get('file', ''))
    if not os.path.isfile(rule_file):
        continue

    with open(rule_file) as f:
        content = f.read()

    # Strip YAML frontmatter if present
    fm_match = re.match(r'^---\s*\n.*?\n---\s*\n', content, re.DOTALL)
    if fm_match:
        content = content[fm_match.end():]

    sections.append(content.strip())

body = '\n\n---\n\n'.join(sections)
# Ensure header ends with a blank line before the body
output = header.rstrip('\n') + '\n\n' + body + '\n'

# Codex auto-truncates AGENTS.md at 32 KiB. Warn on stderr when the codex
# target gets close, so users notice before silent truncation hits.
CODEX_LIMIT = 32 * 1024
WARN_THRESHOLD = int(CODEX_LIMIT * 0.9)
if target == 'codex':
    size = len(output.encode('utf-8'))
    if size >= CODEX_LIMIT:
        sys.stderr.write(
            f"[WARN] AGENTS.md output is {size} bytes — exceeds Codex 32 KiB limit; "
            f"content past the limit will be truncated by Codex. "
            f"Consider raising project_doc_max_bytes or trimming rules.\n"
        )
    elif size >= WARN_THRESHOLD:
        sys.stderr.write(
            f"[WARN] AGENTS.md output is {size} bytes — within 10%% of Codex's "
            f"32 KiB limit. Adding more rules may trigger silent truncation.\n"
        )

print(output, end='')
PYEOF
}

# ---------------------------------------------------------------------------
# Build Claude-specific @-import lines (paths under .claude/rules/ or repo root).
# Claude Code expands @-imports eagerly into the system prompt; using imports
# keeps CLAUDE.md scaffold small and lets the prompt cache invalidate per-rule
# rather than re-hash the full concatenation on any edit. This emission shape
# is Claude-specific (Codex doesn't support @-import; Gemini inlines today).
# Returns the import lines on stdout (no trailing newline).
# ---------------------------------------------------------------------------
_build_claude_imports() {
  python3 - "${WORKSPACE_DIR}/tools/rules/manifest.yaml" \
            "${WORKSPACE_DIR}" <<'PYEOF'
import sys, os, yaml

manifest_path = sys.argv[1]
workspace_dir = sys.argv[2]

with open(manifest_path) as f:
    manifest = yaml.safe_load(f)

rules = manifest.get('rules', {})
sorted_rules = sorted(rules.items(), key=lambda kv: kv[1].get('order', 999))

import_lines = []
for rule_key, rule_meta in sorted_rules:
    targets = rule_meta.get('targets', [])
    if 'claude' not in targets:
        continue
    rule_file = rule_meta.get('file', '')
    abs_path = os.path.normpath(os.path.join(workspace_dir, 'tools/rules', rule_file))
    rel_to_root = os.path.relpath(abs_path, workspace_dir)
    rules_prefix = os.path.join('tools', 'rules') + os.sep
    if rel_to_root.startswith(rules_prefix):
        rule_basename = rel_to_root[len(rules_prefix):]
        import_lines.append(f'- @.claude/rules/{rule_basename}')
    else:
        import_lines.append(f'- @{rel_to_root}')

print('\n'.join(import_lines), end='')
PYEOF
}

# ---------------------------------------------------------------------------
# Main entry point
# ---------------------------------------------------------------------------
rules_adapter_run() {
  log_info "=== Rules adapter ==="

  local agents_header
  agents_header="$(cat <<'HDR'
# AGENTS.md — Cross-CLI Agent Rules

> Generated by `scripts/adapters/rules.sh`. Edit `tools/rules/*.md` instead.

HDR
)"

  local gemini_header
  gemini_header="$(cat <<'HDR'
# GEMINI.md — Cross-CLI Agent Rules

> Generated by `scripts/adapters/rules.sh`. Edit `tools/rules/*.md` instead.

HDR
)"

  local claude_header
  claude_header="$(cat <<'HDR'
# CLAUDE.md — Claude Code entry context for ai-cli-workspace

> Generated by `scripts/adapters/rules.sh`. Edit `tools/rules/*.md` instead.
> 繁體中文優先 · English supported

## 四層載入框架（Claude Code session 載入機制）

```
🔴 Real-time  — session-init.sh hook + CLAUDE.md 本體
🟡 Auto       — rules @-imported（每次 session 必載入）
🟢 On-demand  — skills + commands：說觸發詞才載入
⚪ Skip       — docs/archive、reference docs：手動 Read 即可
```

> 💡 執行 `/load-plan` 動態查看完整清單與 token 估算

## Workspace 維護者指南

本檔案位於 workspace repo root，讀者為「**維護 ai-cli-workspace 本身的人**」。
若你是「**使用 workspace 的一般使用者**」，看到的是裝在 `~/.claude/CLAUDE.md`
（由 install.sh 從 `tools/` 生成），跟本檔案結構雷同但定位不同。

- **SoT 原則**：`tools/` 是真理之源。**不要直接編輯** `.claude/`、`~/.gemini/`、
  `~/.codex/`、`AGENTS.md`、`GEMINI.md`、`CLAUDE.md` —— 它們皆是 `scripts/install.sh`
  的生成物。要改設定請改 `tools/` 底下對應的來源檔。
- **同步流程**：`git pull` workspace → `bash scripts/install.sh --target=all`
  → 重新生成所有產物。
- **新增 skill / agent / rule**：放到 `tools/skills/<name>/SKILL.md` 等對應位置；
  rule 需在 `tools/rules/manifest.yaml` 註冊 targets 與 order。
- **冪等性**：所有 adapter 必須冪等——同一 `install.sh` 重跑應顯示 `Unchanged`。
- **驗證**：commit 前跑 `bash scripts/install.sh --dry-run --target=all` 確認預期變動。

## 進階文件

- `CONTEXT.md` — 跨 CLI 專案脈絡（已透過下方 import 自動載入）
- `docs/INDEX.md` — workspace 文件總索引

## 常駐規則（🟡 自動載入）
HDR
)"

  # 1. Generate AGENTS.md (portable rules that include codex)
  log_info "Generating AGENTS.md..."
  local agents_content
  agents_content="$(_build_rules_for_target "codex" "$agents_header")"
  write_if_changed "${WORKSPACE_DIR}/AGENTS.md" "$agents_content"

  # 2. Generate GEMINI.md (portable rules that include gemini)
  log_info "Generating GEMINI.md..."
  local gemini_content
  gemini_content="$(_build_rules_for_target "gemini" "$gemini_header")"
  write_if_changed "${WORKSPACE_DIR}/GEMINI.md" "$gemini_content"

  # 3. Generate CLAUDE.md (header ending with "## 常駐規則" heading + @-imports).
  #    Claude Code expands @-imports eagerly into the prompt, but per-file cache
  #    granularity beats one monolithic inline blob.
  log_info "Generating CLAUDE.md..."
  local claude_imports
  claude_imports="$(_build_claude_imports)"
  local claude_content
  claude_content="$(printf '%s\n\n%s\n' "$claude_header" "$claude_imports")"
  write_if_changed "${WORKSPACE_DIR}/CLAUDE.md" "$claude_content"

  log_ok "Rules adapter done."
}

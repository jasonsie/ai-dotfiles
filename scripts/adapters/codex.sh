#!/usr/bin/env bash
# scripts/adapters/codex.sh — Generate ~/.codex/config.toml, skills, agents, hooks
#
# Entry point: codex_adapter_run

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "${SCRIPT_DIR}/_common.sh"

WORKSPACE_DIR="${WORKSPACE_DIR:-$(cd "${SCRIPT_DIR}/../.." && pwd)}"

# ---------------------------------------------------------------------------
# Build ~/.codex/hooks.json
# ---------------------------------------------------------------------------
_codex_build_hooks_json() {
  python3 - "${WORKSPACE_DIR}/tools/hooks/manifest.yaml" "${WORKSPACE_DIR}" <<'PYEOF'
import sys, json, yaml

with open(sys.argv[1]) as f:
    manifest = yaml.safe_load(f)

workspace_dir = sys.argv[2]
events = manifest.get('events', {})

hook_list = []

for event_key, event_data in events.items():
    codex_event = event_data.get('codex')
    if not codex_event:
        continue

    script = event_data.get('script', '')
    hook_list.append({
        "event": codex_event,
        "command": ["bash", f"{workspace_dir}/tools/hooks/{script}"],
        "env": {
            "WORKSPACE_CLI_NAME": "codex",
            "WORKSPACE_DIR": workspace_dir
        }
    })

result = {"hooks": hook_list}
print(json.dumps(result, indent=2))
PYEOF
}

# ---------------------------------------------------------------------------
# Build MCP TOML block (for insertion into config.toml)
# ---------------------------------------------------------------------------
_codex_build_mcp_toml() {
  python3 - "${WORKSPACE_DIR}/tools/mcp/servers.yaml" <<'PYEOF'
import sys, yaml

with open(sys.argv[1]) as f:
    data = yaml.safe_load(f)

servers = data.get('servers') or []
lines = []

for srv in servers:
    name = srv.get('name')
    if not name:
        continue
    enabled = srv.get('enabled-for')
    if enabled and 'codex' not in enabled:
        continue

    lines.append(f'[mcp_servers.{name}]')
    stype = srv.get('type', 'stdio')
    lines.append(f'type = "{stype}"')

    if stype == 'http':
        lines.append(f'url = "{srv.get("url", "")}"')
    else:
        cmd = srv.get('command', '')
        lines.append(f'command = "{cmd}"')
        args = srv.get('args', [])
        args_str = ', '.join(f'"{a}"' for a in args)
        lines.append(f'args = [{args_str}]')
        env = srv.get('env', {})
        if env:
            for k, v in env.items():
                lines.append(f'  {k} = "{v}"')
    lines.append('')

print('\n'.join(lines))
PYEOF
}

# ---------------------------------------------------------------------------
# Generate an agent YAML file for Codex
# ---------------------------------------------------------------------------
_agent_md_to_codex_yaml() {
  local agent_file="$1"
  local out_path="$2"

  python3 - "$agent_file" "$out_path" <<'PYEOF'
import sys, re, os, yaml

agent_path = sys.argv[1]
out_path   = sys.argv[2]

with open(agent_path) as f:
    raw = f.read()

fm = {}
body = raw
fm_match = re.match(r'^---\s*\n(.*?)\n---\s*\n', raw, re.DOTALL)
if fm_match:
    try:
        fm = yaml.safe_load(fm_match.group(1)) or {}
    except Exception:
        pass
    body = raw[fm_match.end():]

name        = fm.get('name', os.path.basename(agent_path).replace('.md', ''))
description = fm.get('description', '')

agent_doc = {
    'name': name,
    'description': description,
    'model': 'gpt-5-codex',
    'tools': []
}

os.makedirs(os.path.dirname(out_path) or '.', exist_ok=True)
with open(out_path, 'w') as f:
    yaml.dump(agent_doc, f, allow_unicode=True, default_flow_style=False)
PYEOF
}

# ---------------------------------------------------------------------------
# Render config.toml by substituting {{MCP_BLOCK}} and {{HOOKS_BLOCK}}
# ---------------------------------------------------------------------------
_codex_render_config() {
  local mcp_toml="$1"

  python3 - "${WORKSPACE_DIR}/tools/settings/codex.toml.tmpl" \
            "${WORKSPACE_DIR}" <<PYEOF
import sys, os

with open(sys.argv[1]) as f:
    content = f.read()

workspace_dir = sys.argv[2]

mcp_block = """${mcp_toml}"""

hooks_comment = (
    "# Hooks are configured separately in ~/.codex/hooks.json\\n"
    "# (generated by scripts/adapters/codex.sh)"
)

content = content.replace('# {{MCP_BLOCK}} — generated [mcp_servers.<name>] tables go here',
                           mcp_block if mcp_block.strip() else '# No MCP servers configured')
content = content.replace('# {{HOOKS_BLOCK}} — generated [[hooks.<event>]] arrays go here',
                           hooks_comment)

print(content, end='')
PYEOF
}

# ---------------------------------------------------------------------------
# Main entry point
# ---------------------------------------------------------------------------
codex_adapter_run() {
  log_info "=== Codex adapter ==="

  # 1. Ensure directories
  ensure_dir "${HOME}/.codex"
  ensure_dir "${HOME}/.codex/skills"
  ensure_dir "${HOME}/.codex/agents"

  # 2. Copy local skills (workspace-managed, marker-tracked)
  for skill_dir in "${WORKSPACE_DIR}/tools/skills"/*/; do
    skill_name="$(basename "$skill_dir")"
    if [ -f "${skill_dir}/SKILL.md" ]; then
      ensure_copied_tree "${WORKSPACE_DIR}/tools/skills/${skill_name}" \
                         "${HOME}/.codex/skills/${skill_name}"
    fi
  done

  # 2b. Prune skills previously installed by workspace but now removed from tools/skills/.
  prune_stale_managed "${HOME}/.codex/skills" \
                      "${WORKSPACE_DIR}/tools/skills"

  # 3. Generate agent YAML files
  for agent_file in "${WORKSPACE_DIR}/tools/agents"/*.md; do
    [ -f "$agent_file" ] || continue
    agent_name="$(basename "$agent_file" .md)"
    yaml_path="${HOME}/.codex/agents/${agent_name}.yaml"

    if is_dry_run; then
      log_info "[dry-run] would generate agent: ${yaml_path}"
      summary_track created
    else
      _agent_md_to_codex_yaml "$agent_file" "$yaml_path"
      log_ok "Generated agent: ${yaml_path}"
      summary_track created
    fi
  done

  # 4. Build MCP TOML block
  log_info "Building Codex MCP block..."
  local mcp_toml
  mcp_toml="$(_codex_build_mcp_toml)"

  # 5. Render config.toml
  log_info "Rendering ~/.codex/config.toml..."
  local rendered_config
  rendered_config="$(_codex_render_config "$mcp_toml")"

  write_if_changed "${HOME}/.codex/config.toml" "$rendered_config"

  # 6. Build and write hooks.json
  log_info "Building ~/.codex/hooks.json..."
  local hooks_json
  hooks_json="$(_codex_build_hooks_json)"

  write_if_changed "${HOME}/.codex/hooks.json" "$hooks_json"

  # 7. Validate TOML (python 3.11+)
  if ! is_dry_run && [ -f "${HOME}/.codex/config.toml" ]; then
    if python3 -c "import tomllib; tomllib.load(open('${HOME}/.codex/config.toml','rb'))" \
       2>/dev/null; then
      log_ok "~/.codex/config.toml is valid TOML"
    else
      log_warn "TOML validation skipped (requires python 3.11+ with tomllib)"
    fi
  fi

  log_ok "Codex adapter done."
}
